def add_formula_block(doc, formula_text: str, num_str: str = ""):
    """Формула по центру, номер (1) по правому краю в невидимой таблице."""
    table = doc.add_table(rows=1, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
